#!/usr/bin/env python3
"""One consolidated table: embodiment x camera track x world model, dense only.

Answers "how many rollouts / tasks / instructions does each cell actually hold",
joining two sources that must agree:

  * rollout counts  -> results/reports/sampling_audit.json  (audited: applies the
    non-benchmark exclusions and merges the two Ctrl-World tree variants)
  * task metadata   -> results/reports/dataset_appendix_evidence.json

Emits CSV (for the spreadsheet) and Markdown (for reading in the terminal / docs).

    python3 assets/scripts/audit_sampling_distribution.py --json results/reports/sampling_audit.json
    python3 assets/scripts/make_dataset_appendix_tables.py
    python3 assets/scripts/make_cell_matrix.py
"""
from __future__ import annotations

import csv
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
AUDIT = os.path.join(REPO, "results/reports/sampling_audit.json")
EVID = os.path.join(REPO, "results/reports/dataset_appendix_evidence.json")
OUT_CSV = os.path.join(REPO, "results/reports/cell_matrix.csv")
OUT_MD = os.path.join(REPO, "docs/datasets/cell_matrix.md")

EMB_ORDER = ["humanoid", "bimanual", "single_arm"]
EMB_LABEL = {"humanoid": "humanoid", "bimanual": "bimanual",
             "single_arm": "single_arm"}
VIEW_ORDER = ["MV", "SV"]
LONG_VIEW = {"MV": "multiview", "SV": "singleview"}
MODEL_ORDER = ["dreamgen", "dreamdojo", "ctrlworld"]
MODEL_LABEL = {"dreamgen": "DreamGen", "dreamdojo": "DreamDojo",
               "ctrlworld": "Ctrl-World"}


def main() -> int:
    audit = json.load(open(AUDIT))
    evid = json.load(open(EVID))
    dense = {(c["embodiment"], c["view"], c["model"]): c
             for c in audit["dense_cells"]}
    ev = {(c["embodiment"], c["view"], c["split"]): c for c in evid["cells"]}

    rows = []
    for e in EMB_ORDER:
        for v in VIEW_ORDER:
            mk = ev[(e, LONG_VIEW[v], "makovian")]
            nm = ev[(e, LONG_VIEW[v], "non_makovian")]
            # Task/instruction metadata is a property of the SOURCE cell, so it is
            # shared by every model that renders it; rollout counts are per model.
            shared = dict(
                tasks_mk=mk["task_dirs"], tasks_nm=nm["task_dirs"],
                instr_mk=mk["instructions_distinct"],
                instr_nm=nm["instructions_distinct"],
                views_per_episode=mk["views_per_episode"],
                camera_rigs=mk["camera_rigs"],
                source_fps="/".join(str(x) for x in (mk["source_fps"] or [])),
                source_resolution="/".join(mk["source_resolution"] or []),
                corpus=mk["corpus"],
                src_episodes=mk["episodes_selected"] + nm["episodes_selected"],
            )
            for m in MODEL_ORDER:
                c = dense.get((e, v, m))
                rows.append(dict(
                    embodiment=e, view=v, model=MODEL_LABEL[m],
                    supported="yes" if c else "no",
                    makovian=c["makovian"] if c else 0,
                    non_makovian=c["non_makovian"] if c else 0,
                    dense_rollouts=c["total"] if c else 0,
                    **shared))

    fields = ["embodiment", "view", "model", "supported", "makovian",
              "non_makovian", "dense_rollouts", "src_episodes", "tasks_mk",
              "tasks_nm", "instr_mk", "instr_nm", "views_per_episode",
              "camera_rigs", "source_fps", "source_resolution", "corpus"]
    os.makedirs(os.path.dirname(OUT_CSV), exist_ok=True)
    with open(OUT_CSV, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    # ---- markdown ----
    L = []
    L.append("# Cell matrix: embodiment x camera track x world model (dense)\n")
    L.append(f"Generated by `assets/scripts/make_cell_matrix.py`. Rollout counts are "
             f"the AUDITED ones (`scope_matches_design = "
             f"{audit['scope_matches_design']}`); task metadata comes from the "
             f"dataset evidence file.\n")
    L.append(f"- Dense rollouts: **{audit['dense_total']:,}** "
             f"(DreamGen {audit['model_totals']['dreamgen']:,}, "
             f"DreamDojo {audit['model_totals']['dreamdojo']:,}, "
             f"Ctrl-World {audit['model_totals']['ctrlworld']:,})")
    L.append(f"- All rollouts incl. acceleration: **{audit['grand_total']:,}**")
    L.append(f"- Source corpus: **{evid['totals']['episode_instances']:,}** episode "
             f"instances = **{evid['totals']['distinct_source_episodes']:,}** "
             f"distinct trajectories\n")

    L.append("## Dense rollouts per cell\n")
    L.append("| embodiment | view | " + " | ".join(MODEL_LABEL[m] for m in MODEL_ORDER)
             + " | row total |")
    L.append("|---|---|" + "---|" * (len(MODEL_ORDER) + 1))
    for e in EMB_ORDER:
        for v in VIEW_ORDER:
            cells, tot = [], 0
            for m in MODEL_ORDER:
                c = dense.get((e, v, m))
                if not c:
                    cells.append("n/a")
                    continue
                cells.append(f"{c['makovian']}+{c['non_makovian']} = "
                             f"**{c['total']}**")
                tot += c["total"]
            L.append(f"| {EMB_LABEL[e]} | {v} | " + " | ".join(cells)
                     + f" | {tot} |")
    L.append(f"| **total** | | "
             + " | ".join(f"**{audit['model_totals'][m]:,}**" for m in MODEL_ORDER)
             + f" | **{audit['dense_total']:,}** |\n")

    L.append("## Source cell properties (shared by every model on that cell)\n")
    L.append("| embodiment | view | corpus | src eps | tasks (M+nM) | "
             "instructions (M+nM) | views/ep | rigs | fps | resolution |")
    L.append("|---|---|---|---|---|---|---|---|---|---|")
    seen = set()
    for r in rows:
        k = (r["embodiment"], r["view"])
        if k in seen:
            continue
        seen.add(k)
        L.append(f"| {r['embodiment']} | {r['view']} | {r['corpus']} | "
                 f"{r['src_episodes']} | {r['tasks_mk']}+{r['tasks_nm']} | "
                 f"{r['instr_mk']}+{r['instr_nm']} | {r['views_per_episode']} | "
                 f"{r['camera_rigs']} | {r['source_fps']} | "
                 f"{r['source_resolution']} |")

    L.append("\n## Rollouts per acceleration method\n")
    L.append("| method | rollouts |")
    L.append("|---|---|")
    for m, n in audit["method_totals"].items():
        L.append(f"| {m} | {n:,} |")
    L.append("\n## Totals by family\n")
    L.append("| family | methods | rollouts |")
    L.append("|---|---|---|")
    for g in audit["groups"]:
        L.append(f"| {g['name']} | {len(g['members'])} | {g['total']:,} |")
    L.append(f"| **TOTAL** | | **{audit['grand_total']:,}** |")

    os.makedirs(os.path.dirname(OUT_MD), exist_ok=True)
    open(OUT_MD, "w").write("\n".join(L) + "\n")

    print(f"wrote {os.path.relpath(OUT_CSV, REPO)}  ({len(rows)} rows)")
    print(f"wrote {os.path.relpath(OUT_MD, REPO)}")
    print(f"dense {audit['dense_total']:,} | all {audit['grand_total']:,}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
