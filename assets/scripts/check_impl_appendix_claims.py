#!/usr/bin/env python3
"""Verify every numeric claim in Appendix C against its source of record.

The appendix prose states numbers (self-attention shares, Amdahl ceilings,
divergence counts, PSNR deltas, script counts). Those numbers were true when
written, but the underlying data is regenerated by other scripts, so the prose
can silently drift out of date. This gate re-derives each claim from source and
fails loudly on any mismatch, in the same spirit as
``check_dataset_appendix_claims.py``.

Each check names the claim, the value found in the prose, the value re-derived
from data, and the file the truth came from -- so a failure tells you which
number to fix and where it now comes from.

    python3 assets/scripts/check_impl_appendix_claims.py

Exit code 0 if every claim verifies, 1 otherwise.
"""

from __future__ import annotations

import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TEX = os.path.join(REPO, "assets/paper/appendix/3_implemetation_details.tex")
FIG_TEX = os.path.join(REPO, "assets/paper/appendix/figures/fig_accel_taxonomy.tex")
ACCEL = os.path.join(REPO, "metrics/reports/impl_accel_configs.json")
FINETUNE = os.path.join(REPO, "metrics/reports/finetune_config.json")
BUDGET = os.path.join(REPO, "metrics/reports/time_budget.json")
KNEE = os.path.join(REPO, "metrics/reports/knee_curves.json")
PREP = os.path.join(REPO, "metrics/reports/training_data_prep.json")
QUAL = os.path.join(REPO, "metrics/reports/finetune_qualitative.json")
CKPT_DOC = os.path.join(REPO, "docs/main_results_speedup_and_checkpoint.md")

results = []


def check(name, claimed, actual, source, tol=0.0):
    """Record one claim. Numeric comparison honours `tol`; else exact equality.

    A claim whose prose pattern no longer matches yields None, which must be
    reported as a failure rather than crashing the gate: the usual cause is that
    the sentence was rewritten, and the gate's job is to say so.
    """
    if claimed is None or actual is None:
        results.append({"claim": name, "in_prose": claimed, "from_data": actual,
                        "source": source, "ok": False,
                        "note": "claim not found in prose (pattern no longer matches)"
                                if claimed is None else "value missing from data"})
        return False
    if isinstance(claimed, float) or isinstance(actual, float):
        ok = abs(float(claimed) - float(actual)) <= tol
    else:
        ok = claimed == actual
    results.append({"claim": name, "in_prose": claimed, "from_data": actual,
                    "source": source, "ok": ok})
    return ok


def load(path):
    with open(path) as fh:
        return json.load(fh)


def main():
    prose = open(TEX).read() + open(FIG_TEX).read()
    accel = load(ACCEL)
    fine = load(FINETUNE)
    budget = load(BUDGET)
    knee = load(KNEE)
    prep = load(PREP)

    def has(pattern):
        return re.search(pattern, prose) is not None

    def num(pattern, cast=float):
        m = re.search(pattern, prose)
        return cast(m.group(1).replace(",", "").replace("{", "").replace("}", "")) \
            if m else None

    # ---- 1. script / row counts -------------------------------------------
    check("number of method--cell combinations",
          num(r"covering all \$(\d+)\$ method--cell combinations", int),
          accel["n_scripts_parsed"], "impl_accel_configs.json:n_scripts_parsed")

    # ---- 2. divergence reconciliation ------------------------------------
    check("total parameter divergences",
          num(r"Of the\s*\n?\$(\d+)\$ parameter values", int),
          accel["n_divergences"], "impl_accel_configs.json:n_divergences")
    check("divergences backed by a sweep",
          num(r"\$(\d+)\$\s*\n?are backed by a recorded sweep", int),
          accel["n_divergences"] - accel["n_divergences_undocumented"],
          "impl_accel_configs.json:n_divergences - n_divergences_undocumented")
    check("undocumented divergences",
          num(r"The remaining \$(\d+)\$ are not", int),
          accel["n_divergences_undocumented"],
          "impl_accel_configs.json:n_divergences_undocumented")

    # ---- 3. runnable-but-not-released cells -------------------------------
    check("runnable but unreleased cells",
          num(r"[Ss]eparately, (six|\d+) configurations are runnable but",
              lambda s: 6 if s == "six" else int(s)),
          len(accel["script_without_coverage"]),
          "impl_accel_configs.json:script_without_coverage")

    # ---- 4. generation cells ---------------------------------------------
    check("number of generation configurations",
          num(r"spanning the \$(\d+)\$ generation configurations", int),
          fine["n_generation_cells"], "finetune_config.json:n_generation_cells")

    # ---- 5. self-attention shares and Amdahl ceilings --------------------
    ceil = {k.replace("\n", " "): v for k, v in budget["amdahl_ceilings"].items()}
    dg_mv = ceil["DreamGen 2B MV 16:9"]
    check("DreamGen MV self-attention share (%)",
          num(r"is \$(\d+\.\d+)\\%\$ of generation on the DreamGen multi-view"),
          round(100 * dg_mv["self_attn_share"], 1),
          "time_budget.json:amdahl_ceilings", tol=0.05)
    check("DreamGen MV Amdahl ceiling",
          num(r"cannot exceed \$(\d+\.\d+)\\times\$ on DreamGen"),
          round(dg_mv["max_speedup"], 2),
          "time_budget.json:amdahl_ceilings", tol=0.005)

    dd = [ceil[k] for k in ceil if k.startswith("DreamDojo")]
    dd_lo = round(100 * min(d["self_attn_share"] for d in dd), 1)
    dd_hi = round(100 * max(d["self_attn_share"] for d in dd), 1)
    check("DreamDojo self-attention share low (%)",
          num(r"only \$(\d+\.\d+)\\%\$ to \$\d+\.\d+\\%\$ on the DreamDojo"),
          dd_lo, "time_budget.json:amdahl_ceilings", tol=0.05)
    check("DreamDojo self-attention share high (%)",
          num(r"only \$\d+\.\d+\\%\$ to \$(\d+\.\d+)\\%\$ on the DreamDojo"),
          dd_hi, "time_budget.json:amdahl_ceilings", tol=0.05)
    check("DreamDojo Amdahl ceiling low",
          num(r"\$(\d+\.\d+)\$--\$\d+\.\d+\\times\$ on\s*\n?DreamDojo"),
          round(min(d["max_speedup"] for d in dd), 2),
          "time_budget.json:amdahl_ceilings", tol=0.005)
    check("DreamDojo Amdahl ceiling high",
          num(r"\$\d+\.\d+\$--\$(\d+\.\d+)\\times\$ on\s*\n?DreamDojo"),
          round(max(d["max_speedup"] for d in dd), 2),
          "time_budget.json:amdahl_ceilings", tol=0.005)

    cw = ceil["Ctrl-World SVD U-Net"]
    check("Ctrl-World spatial-attention share (%)",
          num(r"spatial attention is \$(\d+)\\%\$ of wall time", int),
          round(100 * cw["self_attn_share"]),
          "time_budget.json:ctrlworld_profile", tol=0.5)
    check("Ctrl-World Amdahl ceiling",
          num(r"or \$(\d+\.\d+)\\times\$ on Ctrl-World"),
          round(cw["max_speedup"], 2),
          "time_budget.json:amdahl_ceilings", tol=0.005)
    check("Ctrl-World ceiling quoted in the schematic caption",
          num(r"bounds it near \$(\d+\.\d+)\\times\$"),
          round(cw["max_speedup"], 2),
          "time_budget.json:amdahl_ceilings", tol=0.005)

    # ---- 6. instrumented run count ---------------------------------------
    n_dit = sum(v["n_runs"] for v in budget["dit_aggregated"].values())
    claimed_runs = num(r"\$(\d[\d{},]*)\$ instrumented runs", int)
    check("instrumented DiT runs", claimed_runs, n_dit,
          "time_budget.json:dit_aggregated[*].n_runs")
    check("instrumented run count repeated in figure caption",
          num(r"aggregate \$(\d[\d{},]*)\$ instrumented runs", int), n_dit,
          "time_budget.json:dit_aggregated[*].n_runs")

    # ---- 7. checkpoint-ablation PSNR deltas ------------------------------
    doc = open(CKPT_DOC).read()
    for label, pat in (
        ("Ctrl-World bimanual MV finetuning gain",
         r"bimanual multiview PSNR rises from\s*\n?>?\s*\*\*[\d.]+ . [\d.]+ dB \(\+([\d.]+) dB\)\*\*"),
        ("Ctrl-World humanoid MV finetuning gain",
         r"humanoid multiview PSNR rises \*\*[\d.]+ . [\d.]+ dB \(\+([\d.]+) dB\)\*\*"),
    ):
        m = re.search(pat, doc)
        if not m:
            results.append({"claim": label, "in_prose": None, "from_data": None,
                            "source": CKPT_DOC, "ok": False,
                            "note": "could not locate the claim in the source doc"})
            continue
        key = "bimanual" if "bimanual" in label else "humanoid"
        claimed = num(r"\$\+(\d+\.\d+)\$\\,dB on Ctrl-World %s\s*\n?multi-view" % key)
        check(label, claimed, float(m.group(1)), "docs/main_results_speedup_and_checkpoint.md",
              tol=0.005)

    # ---- 8. qualitative invariants ---------------------------------------

    # ---- 7c. finetuning qualitative figure -------------------------------
    # The figure's per-row PSNR must be the value the rollout recorded, and the
    # prose must not claim a mechanism the figure does not show.
    qual = load(QUAL)
    for e in qual["episodes"]:
        check("qualitative figure PSNR gain (%s)" % e["cell"],
              round(e["psnr_finetuned"] - e["psnr_base"], 2), e["psnr_gain"],
              "finetune_qualitative.json:psnr_gain", tol=0.011)
        results.append({
            "claim": "qualitative figure shows a real gain (%s)" % e["cell"],
            "in_prose": True, "from_data": e["psnr_gain"] > 0,
            "source": "finetune_qualitative.json", "ok": e["psnr_gain"] > 0})
    check("qualitative figure is cited in the prose",
          has(r"\\Cref\{fig:supp_finetune_qual\}"), True,
          "3_implemetation_details.tex")
    check("qualitative figure samples >1 timepoint",
          len(qual["sampled_fractions"]) >= 3, True,
          "finetune_qualitative.json:sampled_fractions")

    # ---- 7b. training corpus construction --------------------------------
    hum = [s for s in prep["dreamgen"]["chains"]["humanoid_multiview_seg16"]["stages"]
           if "clips" in s]
    bim = [s for s in prep["dreamgen"]["chains"]["bimanual_multiview_seg16"]["stages"]
           if "clips" in s]
    check("required consecutive frames per training example",
          num(r"A training example requires \$(\d+)\$ consecutive frames", int),
          hum[0]["min_frames"], "training_data_prep.json:min_frames")
    check("humanoid usable clips before preprocessing",
          num(r"leaving only\s*\n?\$(\d+)\$ of \$\d+\$ clips", int),
          hum[0]["usable"], "training_data_prep.json:humanoid stage 0 usable")
    check("humanoid total clips before preprocessing",
          num(r"leaving only\s*\n?\$\d+\$ of \$(\d+)\$ clips", int),
          hum[0]["clips"], "training_data_prep.json:humanoid stage 0 clips")
    check("humanoid usable fraction before preprocessing (%)",
          num(r"of \$\d+\$ clips \(\$(\d+)\\%\$\)", int),
          round(100.0 * hum[0]["usable"] / hum[0]["clips"]),
          "training_data_prep.json:humanoid stage 0", tol=0.5)
    check("humanoid usable clips after preprocessing",
          num(r"restores usable data, from \$\d+\$ to\s*\n?\$(\d+)\$ clips", int),
          hum[-1]["usable"], "training_data_prep.json:humanoid final usable")
    check("humanoid repair factor",
          num(r"\$(\d+\.\d+)\\times\$\); on the bimanual corpus"),
          round(hum[-1]["usable"] / float(hum[0]["usable"]), 1),
          "training_data_prep.json:humanoid usable ratio", tol=0.05)
    check("bimanual augmentation factor",
          num(r"acts as a \$(\d+\.\d+)\\times\$ augmentation"),
          round(bim[-1]["usable"] / float(bim[0]["usable"]), 1),
          "training_data_prep.json:bimanual usable ratio", tol=0.05)
    check("bimanual clip counts",
          num(r"\(\$(\d+) \\rightarrow \d+\$\)", int),
          bim[0]["usable"], "training_data_prep.json:bimanual stage 0 usable")
    check("bimanual clip counts after",
          num(r"\(\$\d+ \\rightarrow (\d+)\$\)", int),
          bim[-1]["usable"], "training_data_prep.json:bimanual final usable")
    check("humanoid grid stitch fps",
          num(r"was assembled at \$(\d+)\$\\,fps", int),
          int(hum[0]["fps"]), "training_data_prep.json:humanoid stage 0 fps")
    check("bimanual grid native fps",
          num(r"retained\s*\n?its native \$(\d+)\$\\,fps", int),
          int(bim[0]["fps"]), "training_data_prep.json:bimanual stage 0 fps")
    seg = prep["dreamgen"]["stage_params"]["segment_humanoid"]
    check("segment window (s)",
          num(r"overlapping \$(\d+)\$\\,s\s*\n?windows", int), int(seg["win"]),
          "training_data_prep.json:stage_params.segment_humanoid.win")
    check("segment stride (s)",
          num(r"at a \$(\d+)\$\\,s stride", int), int(seg["stride"]),
          "training_data_prep.json:stage_params.segment_humanoid.stride")
    # Ctrl-World latent pipeline.
    cwp = prep["ctrlworld"]
    check("Ctrl-World source fps",
          num(r"the \$(\d+)\$\\,fps\s*\n?multi-view recordings", int), cwp["source_fps"],
          "training_data_prep.json:ctrlworld.source_fps")
    check("Ctrl-World downsample stride",
          num(r"subsampled by a stride of \$(\d+)\$", int),
          cwp["downsample_stride"], "training_data_prep.json:ctrlworld.downsample_stride")
    check("Ctrl-World target fps",
          num(r"stride of \$\d+\$ to \$(\d+)\$\\,fps", int), cwp["target_fps"],
          "training_data_prep.json:ctrlworld.target_fps")
    check("Ctrl-World action dimensionality",
          num(r"a\s*\n?\$(\d+)\$-D end-effector pose action", int), cwp["action_dim"],
          "training_data_prep.json:ctrlworld.action_dim")
    check("Ctrl-World latent corpus recorded as a gap",
          has(r"Ctrl-World latent corpus\s*\n?was not retained"),
          any("latent corpus" in g["quantity"] for g in prep["gaps"]),
          "training_data_prep.json:gaps")
    # The frame-rate mismatch must be disclosed with the measured numbers.
    mm = prep["fps_mismatch"]
    check("a frame-rate mismatch was detected",
          has(r"clips are stored at \$\d+\$\\,fps"), len(mm) == 1,
          "training_data_prep.json:fps_mismatch")
    if mm:
        check("mismatched corpus fps on disk",
              num(r"clips are stored at \$(\d+)\$\\,fps", int),
              int(mm[0]["fps_on_disk"]), "training_data_prep.json:fps_mismatch")
        check("mismatched corpus reported fps",
              num(r"declares a rate of \$(\d+)\$\\,fps", int),
              int(mm[0]["fps_reported_to_model"]), "training_data_prep.json:fps_mismatch")
        check("mismatch relative error (%)",
              num(r"frame rate \$(\d+)\\%\$ below the motion", int),
              round(100 * mm[0]["relative_error"]),
              "training_data_prep.json:fps_mismatch.relative_error", tol=0.5)

    # The no-LoRA claim must match what the extractor found, not just be asserted.
    # Test the structured fact (every family's Adaptation row says full finetune),
    # not the presence of the substring "LoRA" -- the data note legitimately
    # contains the phrase "no LoRA", which a substring test would misread.
    adaptation_rows = [v for k, v in (
        ("ctrlworld", fine["ctrlworld"]), ("dreamgen", fine["dreamgen"]),
        ("dreamdojo", fine["dreamdojo"]))]
    check("full-finetune / no-LoRA claim",
          bool(re.search(r"No LoRA or other\s*\n?parameter-efficient adapter is used", prose)),
          ("full finetune" in fine["adaptation"]
           and "no LoRA" in fine["adaptation"]
           and len(adaptation_rows) == 3),
          "finetune_config.json:adaptation")
    # The seed heterogeneity claim must match the per-family seeds.
    seeds = next((g["per_family_seed"] for g in fine["gaps"]
                  if g["quantity"] == "rollout seed"), {})
    check("Ctrl-World rollouts are unseeded",
          has(r"Ctrl-World configurations are\s*\n?unseeded"),
          seeds.get("Ctrl-World") == "unseeded",
          "finetune_config.json:gaps[rollout seed]")
    check("seeding is not uniform across families",
          has(r"Seeding is \\emph\{not\} uniform across families"),
          len(set(seeds.values())) > 1,
          "finetune_config.json:gaps[rollout seed]")
    # Negative results must actually be present in the parsed sweeps.
    slower = any(p["speedup"] < 1.0 for panel in knee["panels"]
                 for p in panel["points"])
    check("sweeps contain configurations slower than dense",
          has(r"configurations slower than dense fall to the left"), slower,
          "knee_curves.json:panels[*].points[*].speedup")

    # ---- report ----------------------------------------------------------
    bad = [r for r in results if not r["ok"]]
    width = max(len(r["claim"]) for r in results)
    for r in results:
        print("%s %-*s prose=%-10s data=%-10s  <- %s" % (
            "PASS" if r["ok"] else "FAIL", width, r["claim"],
            r["in_prose"], r["from_data"], r["source"]))
        if r.get("note"):
            print("      note: %s" % r["note"])
    print("")
    print("%d claims checked, %d passed, %d failed" % (
        len(results), len(results) - len(bad), len(bad)))
    if bad:
        print("")
        print("Appendix C contains numbers that no longer match their source.")
        print("Fix the prose (or regenerate the data) before building the paper.")
        return 1
    print("Every numeric claim in Appendix C is backed by its source of record.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
