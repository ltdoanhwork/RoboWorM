"""Qualitative intuition figures for the three adapted foundation-model metrics.

One figure per metric (Visual Integrity, Text Alignment, Active Motion Continuity):
a LOW row above a HIGH row, each row a frame strip of the **analysis clip** -- the
exact video that produced the number (same view crop, same 5 fps sampling, same
256x192 grid, conditioning frame dropped), so the figure cannot show a different
video from the one that was scored.

The clips and their gated values are taken from the qualitative report
(`results/reports/nr_qualitative/`), which is generated by
`assets/scripts/make_nr_qualitative_report.py` and reads values through
`table_dense_nr.gated()` -- i.e. the same numbers the paper tables print. This
script only parses that report's `index.html`; it never re-scores anything, so the
figures cannot drift from the tables.

Pair selection is pinned in `PICK` rather than "take the extreme", because two of the
three columns carry comparison restrictions: AMC is not comparable across embodiments
and Text Alignment is not comparable across prompts, so a low/high pair must be chosen
to respect the restriction it is printed under.

Usage (needs cv2 + matplotlib -- use the dreamgen venv):
  models/dreamgen/.venv/bin/python assets/scripts/make_nr_intuition_figures.py
  ... --list      # print every exemplar card in the report and exit
"""
import argparse
import html
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
import paper_fig_style as style  # noqa: E402

# (key, filename stem, unit shown on the figure)
METRICS = {
    'visual_integrity': ('fig_nr_intuition_visual_integrity', 'CLIP-IQA+ $p_{10}\\times100$'),
    'text_condition_alignment': ('fig_nr_intuition_text_alignment', 'CLIPScore [0,100]'),
    'active_motion_continuity': ('fig_nr_intuition_amc', 'activity-weighted VFI gain $\\times100$'),
}

# Which exemplar goes in which row, by the clip id prefix the report file names carry
# (`--list` prints every candidate). None = "take the most extreme card of that end".
# The extremes are NOT always the right choice: each of these columns carries a
# comparison restriction, and a figure that crosses it teaches the reader the wrong
# reading even when both numbers are correct.
PICK = {
    # Fails the GT-is-ceiling audit -> may not rank models. Both rows are therefore the
    # same model family (dreamgen / humanoid); the report's own extreme pair spans two
    # models, which would invite exactly the ranking this column may not support.
    'visual_integrity': {'bad': '493efce676', 'good': '23bb1d64a2'},
    # Paired-only: absolute CLIPScore is not comparable across captions. Both rows are
    # humanoid `static` views so the view geometry is held fixed, and both prompts are
    # printed so the reader can see the comparison is illustrative, not a ranking.
    'text_condition_alignment': {'bad': '2bc3e6cf4b', 'good': 'f83f88d23c'},
    # NOT comparable across embodiments (GR1 video is intrinsically less interpolable),
    # so both rows are one configuration: dreamdojo / single_arm / static.
    'active_motion_continuity': {'bad': '156553324c', 'good': '47d9cfa8c3'},
}

N_FRAMES = 5          # frames per strip
FIG_W = 5.5           # inches = the ICLR \textwidth, so \linewidth does NOT rescale
                      # the figure: at 7in everything was silently shrunk to 79% and the
                      # 8pt labels printed at 6.3pt.
CARD_RE = re.compile(
    r'<figure class="card">\s*'
    r'<span class="badge (?P<cls>\w+)">(?P<label>[^&]*)&nbsp;(?P<val>[\d.]+)</span>\s*'
    r'<video src="(?P<clip>clips/[^"]+)"',
    re.S)
META_RE = re.compile(
    r'<div class="meta"><b>(?P<model>[^<]*)</b>[^&]*&middot;\s*'
    r'(?P<emb>[\w]+)\s*&middot;\s*mount <b>(?P<mount>[^<]*)</b>\s*&middot;\s*'
    r'view (?P<view>[^<]*)</div>\s*'
    r'<div class="path">(?P<path>[^<]*)</div>\s*'
    r'(?:<div class="prompt">prompt: &ldquo;(?P<prompt>.*?)&rdquo;</div>)?', re.S)


def parse_report(index):
    """Every non-pair gallery card in the report, as dicts, tagged with its metric."""
    text = index.read_text()
    cards = []
    for m in CARD_RE.finditer(text):
        tail = text[m.end():m.end() + 2000]
        meta = META_RE.search(tail)
        stem = Path(m.group('clip')).name
        # clips are named `<key>_<end>_<id10>.mp4`; actor_motion uses the mount as end.
        key = next((k for k in list(METRICS) + ['actor_motion_raw'] if stem.startswith(k)), None)
        if key is None:
            continue
        end = stem[len(key) + 1:].rsplit('_', 1)[0]
        cards.append(dict(
            key=key, end=end, cid=stem.rsplit('_', 1)[1].split('.')[0],
            cls=m.group('cls'), label=m.group('label').strip(),
            value=float(m.group('val')), clip=index.parent / m.group('clip'),
            model=meta.group('model') if meta else '?',
            emb=meta.group('emb') if meta else '?',
            mount=meta.group('mount') if meta else '?',
            view=meta.group('view') if meta else '?',
            path=html.unescape(meta.group('path')) if meta else '',
            prompt=html.unescape(meta.group('prompt') or '') if meta else '',
        ))
    return cards


def choose(cards, key):
    """The (low, high) exemplar pair for one metric."""
    ends = {'bad': [], 'good': []}
    for c in cards:
        if c['key'] == key and c['end'] in ends:
            ends[c['end']].append(c)
    if not ends['bad'] or not ends['good']:
        sys.exit(f'{key}: report has no bad/good gallery')
    out = {}
    for end in ('bad', 'good'):
        want = PICK[key][end]
        pool = ends[end]
        hit = next((c for c in pool if c['cid'].startswith(want)), None) if want else None
        if want and hit is None:
            sys.exit(f'{key}/{end}: no exemplar with id prefix {want!r}')
        # Galleries are printed worst-first / best-first, so index 0 is the extreme.
        out[end] = hit or pool[0]
    return out['bad'], out['good']


def strip(clip, n):
    """`n` evenly spaced RGB frames of a clip, first and last included."""
    import cv2
    import numpy as np
    cap = cv2.VideoCapture(str(clip))
    frames = []
    while True:
        ok, f = cap.read()
        if not ok:
            break
        frames.append(cv2.cvtColor(f, cv2.COLOR_BGR2RGB))
    cap.release()
    if not frames:
        sys.exit(f'{clip}: no frames decoded')
    idx = np.linspace(0, len(frames) - 1, min(n, len(frames))).round().astype(int)
    return [frames[i] for i in idx], len(frames)


def attach_records(cards, run):
    """Add `method` and the record's own fields from the scored record.

    The report page does not print the acceleration method or the motion covariate, but
    the galleries draw from every method, so a figure that omits the method could
    silently show an accelerated clip as if it were the model's dense output. The clip
    file name carries the first 10 chars of the record id, and records are `<id>.json`.
    """
    import json
    res = run / 'results'
    for c in cards:
        hits = sorted(res.glob(f'{c["cid"]}*.json'))
        if not hits:
            c['method'] = '?'
            continue
        r = json.loads(hits[0].read_text())
        c['method'] = str(r.get('method', '?'))
        c['actor'] = r.get('actor_motion_raw')
        c['n_active'] = r.get('actor_n_active_pairs')
        c['record'] = hits[0]
    return cards


def draw(key, low, high, out_dir, formats):
    import matplotlib
    matplotlib.use('Agg')
    style.apply(matplotlib)
    import matplotlib.pyplot as plt

    stem, unit = METRICS[key]
    title, cap_low, cap_high = LEGEND[key]
    rows = [('low', low, cap_low), ('high', high, cap_high)]
    strips = {tag: strip(c['clip'], N_FRAMES) for tag, c, _ in rows}
    ncol = max(len(s[0]) for s in strips.values())
    h, w = strips['low'][0][0].shape[:2]
    label_w = 0.245                     # fraction of the figure width for the row label
    cell_w = FIG_W * (1 - label_w) / ncol
    head_in = 0.26                      # title only; the explanation is the LaTeX caption
    # Text Alignment is scored against the prompt, so the prompt is part of the evidence;
    # it goes in a footer band rather than in the label cell, which is only ~55pt tall.
    prompts = [(tag, c['prompt']) for tag, c, _ in rows] \
        if key == 'text_condition_alignment' else []
    prompt_lines = {t: textwrap.wrap(p, 92) for t, p in prompts if p}
    foot_in = (0.09 + 0.092 * sum(len(v) for v in prompt_lines.values())
               if prompt_lines else 0.0)
    fig_h = 2 * cell_w * h / w + head_in + foot_in
    fig = plt.figure(figsize=(FIG_W, fig_h), dpi=300)

    colors = {'low': '#a93226', 'high': '#1e6f4a'}
    top = 1 - head_in / fig_h
    row_h = (top - foot_in / fig_h) / 2

    def inch(y):                        # inches from the top -> figure fraction
        return 1 - y / fig_h

    fig.text(0.004, inch(0.115), title, fontsize=8.0, va='center', ha='left',
             color='#111111')
    fig.text(0.996, inch(0.115), unit, fontsize=7.0, va='center', ha='right',
             color='#555555')

    for r, (tag, c, cap) in enumerate(rows):
        frames, n_total = strips[tag]
        y0 = top - (r + 1) * row_h
        for j, fr in enumerate(frames):
            ax = fig.add_axes([label_w + j * (1 - label_w) / ncol, y0,
                               (1 - label_w) / ncol, row_h])
            ax.imshow(fr)
            ax.set_xticks([])
            ax.set_yticks([])
            for s in ax.spines.values():
                s.set_edgecolor('white')
                s.set_linewidth(0.6)

        ax = fig.add_axes([0.004, y0, label_w - 0.012, row_h])
        ax.axis('off')
        ax.add_patch(plt.Rectangle((0, 0), 1, 1, transform=ax.transAxes,
                                   facecolor=colors[tag], alpha=0.06, lw=0))
        digits = 3 if key == 'text_condition_alignment' else 2
        row_pt = row_h * fig_h * 72       # the label cell is only ~55pt tall
        # Lay the label out in POINTS from the top of the cell, converted to axes
        # fraction. Stacking by eyeballed axes offsets overprinted the next row as soon
        # as a caption wrapped to a third line. Three blocks is the hard budget here;
        # provenance (model / method / embodiment) is stated in the LaTeX caption instead,
        # where it is set in the document font and costs no space in the cell.
        blocks = [
            (f'{"LOW" if tag == "low" else "HIGH"}   {c["value"]:.{digits}f}',
             9.5, colors[tag], 'bold'),
            (cap, 6.0, '#222222', 'normal'),
        ]
        # On AMC the motion covariate is part of the evidence: the score must NOT track
        # motion amount, and the reader can only check that if both numbers are printed.
        if key == 'active_motion_continuity' and c.get('actor') is not None:
            blocks.append((f'Actor Activity {c["actor"]:.2f} px/frame',
                           5.6, '#777777', 'normal'))
        y_pt = 3.0
        for txt, size, col, weight in blocks:
            ax.text(0.05, 1 - y_pt / row_pt, txt, fontsize=size, color=col, va='top',
                    ha='left', fontweight=weight, linespacing=1.25,
                    transform=ax.transAxes)
            y_pt += (txt.count('\n') + 1) * size * 1.25 + 4.0

    # Footer: the prompt each row was scored against (Text Alignment only). Stacked
    # upwards from the bottom edge, so a two-line prompt grows into the footer band
    # rather than up into the frame strip above it.
    y_in = 0.040
    for tag in ('high', 'low'):
        lines = prompt_lines.get(tag)
        if not lines:
            continue
        fig.text(0.004, y_in / fig_h,
                 f'{tag}: \u201c' + '\n'.join(lines) + '\u201d',
                 fontsize=5.8, va='bottom', ha='left', style='italic',
                 color=colors[tag], linespacing=1.3)
        y_in += 0.092 * len(lines)

    out_dir.mkdir(parents=True, exist_ok=True)
    for ext in formats:
        p = out_dir / f'{stem}.{ext}'
        fig.savefig(p, bbox_inches='tight', pad_inches=0.012)
        try:
            print(f'wrote {p.relative_to(ROOT)}')
        except ValueError:
            print(f'wrote {p}')
    plt.close(fig)


# (short title, low-row tag, high-row tag). Anything longer belongs in the LaTeX caption.
LEGEND = {
    'visual_integrity': (
        'Visual Integrity: the $10$th percentile over frames',
        'blocking and smearing;\nsurfaces lose all detail',
        'sharp edges, objects\nreadable in every frame'),
    'text_condition_alignment': (
        'Text Alignment: scored against the task clause',
        'commanded objects are\nnot recognisably depicted',
        'commanded objects and\naction are visible'),
    'active_motion_continuity': (
        'Active Motion Continuity: VFI gain over a frame copy',
        'motion pops and teleports;\ninterpolation cannot predict it',
        'motion is continuous;\ninterpolation predicts it'),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--report', type=Path, default=ROOT / 'results/reports/nr_qualitative')
    ap.add_argument('--run', type=Path,
                    default=ROOT / 'metrics/WorldScore/results/dense_nr_full')
    ap.add_argument('--out', type=Path, default=ROOT / 'assets/paper/figures')
    ap.add_argument('--formats', nargs='+', default=['pdf'],
                    help='pdf is what the paper includes; add png for a quick preview')
    ap.add_argument('--only', nargs='+', choices=list(METRICS), default=list(METRICS))
    ap.add_argument('--list', action='store_true', help='print all exemplar cards, exit')
    a = ap.parse_args()

    cards = attach_records(parse_report(a.report / 'index.html'), a.run)
    if a.list:
        for c in sorted(cards, key=lambda c: (c['key'], c['end'], c['value'])):
            print(f'{c["key"]:26s} {c["end"]:7s} {c["value"]:8.3f} {c["cid"]}  '
                  f'{c["model"]:20s} {c.get("method", "?"):12s} {c["emb"]:10s} '
                  f'{c["mount"]:7s} {c["view"]:16s} {c["path"]}')
        return
    for key in a.only:
        low, high = choose(cards, key)
        draw(key, low, high, a.out, a.formats)


if __name__ == '__main__':
    main()
