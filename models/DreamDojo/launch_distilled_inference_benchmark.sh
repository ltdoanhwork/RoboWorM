#!/bin/bash
# ==============================================================================
# DreamDojo Distilled Model Inference Benchmark
# ==============================================================================
# Generates videos using the distilled (student) model with DMD2 (4 steps).
# The distilled model uses KV cache + causal attention for streaming inference.
#
# NOTE: Currently only 2B distilled checkpoints are configured in DreamDojo.
#       For 14B distilled, a distillation pipeline must be run first.
#       See docs/DISTILL.md for the 3-stage distillation process:
#         Stage 1: Teacher generation (launch_teacher_gen.sh)
#         Stage 2: Warmup training (launch_warmup.sh)
#         Stage 3: Self-forcing (launch_self_forcing.sh)
#
# Prerequisites:
#   1. A distilled checkpoint (e.g., from self-forcing training)
#   2. Pre-computed CR1 empty-string text embeddings
#   3. Zero-action .npy files (auto-generated by this script)
# ==============================================================================
set -ex

# ---- Environment ----
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export PYTHONPATH="${SCRIPT_DIR}:${PYTHONPATH}"
export OMP_NUM_THREADS=8
export TORCH_NCCL_ENABLE_MONITORING=0
export TORCH_NCCL_HEARTBEAT_TIMEOUT_SEC=1800
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True
export CUDA_MODULE_LOADING=LAZY

# ---- Virtual environment ----
VENV="/pfss/mlde/workspaces/mlde_wsp_IAS_SAMMerge/VLA/doanh/cosmos-predict2.5/.venv/bin/activate"
source "${VENV}"

# ---- Paths ----
# Update these paths to point to your distilled checkpoint
DISTILL_CKPT_DIR="/pfss/mlde/workspaces/mlde_wsp_IAS_SAMMerge/VLA/doanh/video_world/checkpoints/dreamdojo/distilled"
BATCH_INPUT="/pfss/mlde/workspaces/mlde_wsp_IAS_SAMMerge/VLA/doanh/video_world/VLA-Humanoid/output/dream_gen_benchmark/cosmos_predict2_2b_gr1_env/batch_input.json"
OUTPUT_DIR="/pfss/mlde/workspaces/mlde_wsp_IAS_SAMMerge/VLA/doanh/video_world/dream_gen_benchmark/output_dreamdojo_distilled"
CR1_EMBEDDINGS="${SCRIPT_DIR}/datasets/cr1_empty_string_text_embeddings.pt"
CONFIG_FILE="cosmos_predict2/_src/predict2/interactive/configs/config_distill.py"

# ---- Model config ----
EXPERIMENT="cosmos_predict2p5_2B_action_gr00t_gr1_self_forcing_no_s3"
RESOLUTION="256,320"     # Distilled models typically use lower resolution
NUM_STEPS=4              # DMD2 uses 4 denoising steps (vs ~35 for teacher)
MAX_FRAMES=13
SEED=1
NUM_GPUS=2

# ---- Step 1: Prepare zero-action .npy files ----
ACTIONS_DIR="${OUTPUT_DIR}/zero_actions"
DISTILL_INPUT="${OUTPUT_DIR}/distill_batch_input.json"

echo "Preparing zero-action .npy files and distilled batch input..."
python -c "
import json
import numpy as np
import os

batch_input_path = '${BATCH_INPUT}'
actions_dir = '${ACTIONS_DIR}'
distill_input_path = '${DISTILL_INPUT}'
output_dir = '${OUTPUT_DIR}'
chunk_size = 12
action_dim = 384

os.makedirs(actions_dir, exist_ok=True)

with open(batch_input_path, 'r') as f:
    entries = json.load(f)

distill_entries = []
for i, entry in enumerate(entries):
    # Create zero-action .npy file
    action_path = os.path.join(actions_dir, f'zero_action_{i:04d}.npy')
    np.save(action_path, np.zeros((chunk_size, action_dim), dtype=np.float32))

    basename = os.path.splitext(os.path.basename(entry['input_video']))[0]
    distill_entries.append({
        'input_video': entry['input_video'],
        'input_action': action_path,
        'output_video': os.path.join(output_dir, f'{basename}.mp4'),
    })

with open(distill_input_path, 'w') as f:
    json.dump(distill_entries, f, indent=2)

print(f'Created {len(distill_entries)} entries with zero actions')
"

# ---- Step 2: Run distilled inference ----
echo "Starting distilled inference with ${NUM_GPUS} GPUs..."
echo "Experiment: ${EXPERIMENT}"
echo "Checkpoint: ${DISTILL_CKPT_DIR}"
echo "Num steps: ${NUM_STEPS} (vs ~35 for teacher)"

torchrun --nproc_per_node=${NUM_GPUS} --master_port=12342 \
    -m cosmos_predict2._src.predict2.interactive.inference.action_video2world \
    --config="${CONFIG_FILE}" \
    --experiment="${EXPERIMENT}" \
    --ckpt_path "${DISTILL_CKPT_DIR}" \
    --input_json "${DISTILL_INPUT}" \
    --resolution "${RESOLUTION}" \
    --fps 10.0 \
    --num_steps ${NUM_STEPS} \
    --seed ${SEED} \
    --start_frame_idx 0 \
    --max_frames ${MAX_FRAMES} \
    --context_parallel_size ${NUM_GPUS} \
    --torch_compile

echo "Distilled inference complete. Results saved to: ${OUTPUT_DIR}"
